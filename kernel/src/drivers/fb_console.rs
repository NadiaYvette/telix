//! Framebuffer text console for kernel debug output.
//!
//! Renders characters to a linear framebuffer (UEFI GOP, VBE, or
//! virtio-gpu scanout) using an embedded 8×16 bitmap font.  Hooks
//! into the serial print path so every `println!()` also appears on
//! screen.  Initialized after the MMU is enabled.  The firmware
//! reports a physical address; we route it through PHYS_DIRECT_MAP
//! (#235 Piece A) so the runtime put-pixel path doesn't depend on
//! the PML4[0] identity map.

use core::sync::atomic::{AtomicBool, AtomicU32, AtomicUsize, Ordering};

// ── Framebuffer state ────────────────────────────────────────────────

static FB_ADDR: AtomicUsize = AtomicUsize::new(0);
static FB_PITCH: AtomicU32 = AtomicU32::new(0);
static FB_WIDTH: AtomicU32 = AtomicU32::new(0);
static FB_HEIGHT: AtomicU32 = AtomicU32::new(0);
static FB_READY: AtomicBool = AtomicBool::new(false);

// Cursor position (character grid).
static CUR_X: AtomicU32 = AtomicU32::new(0);
static CUR_Y: AtomicU32 = AtomicU32::new(0);

// Font metrics.
const GLYPH_W: u32 = 8;
const GLYPH_H: u32 = 16;

// Colors (XRGB8888).
const FG_COLOR: u32 = 0x00CCCCCC; // light grey
const BG_COLOR: u32 = 0x00000000; // black

/// Initialize the framebuffer console from bootloader-provided info.
/// Must be called after MMU enable (uses PHYS_DIRECT_MAP).
pub fn init() {
    let info = match crate::firmware::framebuffer_info() {
        Some(i) => i,
        None => return,
    };
    if info.addr == 0 || info.width == 0 || info.height == 0 {
        return;
    }

    // #235 Piece A: route firmware-reported PA through PHYS_DIRECT_MAP
    // so all FB writes work after PML4[0] is unmapped.  PHYS_DIRECT_MAP
    // currently covers PA 0..4 GiB (4 × 1 GiB gigapages from boot.S),
    // which catches the typical QEMU std-VGA / OVMF GOP framebuffer.
    let fb_kva = crate::mm::page::phys_to_kva(info.addr as usize);

    FB_ADDR.store(fb_kva, Ordering::Relaxed);
    FB_PITCH.store(info.pitch, Ordering::Relaxed);
    FB_WIDTH.store(info.width, Ordering::Relaxed);
    FB_HEIGHT.store(info.height, Ordering::Relaxed);

    // Clear screen to background color.
    let fb = fb_kva as *mut u32;
    let stride = info.pitch / 4; // pixels per row (32-bit)
    for y in 0..info.height {
        for x in 0..info.width {
            unsafe {
                *fb.add((y * stride + x) as usize) = BG_COLOR;
            }
        }
    }

    FB_READY.store(true, Ordering::Release);

    let cols = info.width / GLYPH_W;
    let rows = info.height / GLYPH_H;
    crate::println!(
        "  Framebuffer console: {}x{} px, {}x{} chars",
        info.width, info.height, cols, rows
    );
}

/// Returns true if the framebuffer console is initialized.
#[inline]
pub fn available() -> bool {
    FB_READY.load(Ordering::Acquire)
}

/// Write a string to the framebuffer console.  Called from serial _print().
pub fn write_str(s: &str) {
    if !available() {
        return;
    }
    for b in s.bytes() {
        putc(b);
    }
}

/// Write a single character to the framebuffer console.
fn putc(c: u8) {
    let fb = FB_ADDR.load(Ordering::Relaxed);
    let pitch = FB_PITCH.load(Ordering::Relaxed);
    let scr_w = FB_WIDTH.load(Ordering::Relaxed);
    let scr_h = FB_HEIGHT.load(Ordering::Relaxed);
    let cols = scr_w / GLYPH_W;
    let rows = scr_h / GLYPH_H;

    let mut cx = CUR_X.load(Ordering::Relaxed);
    let mut cy = CUR_Y.load(Ordering::Relaxed);

    match c {
        b'\n' => {
            cx = 0;
            cy += 1;
        }
        b'\r' => {
            cx = 0;
        }
        b'\t' => {
            cx = (cx + 8) & !7;
        }
        0x08 => {
            // Backspace.
            if cx > 0 {
                cx -= 1;
            }
        }
        _ => {
            if cx >= cols {
                cx = 0;
                cy += 1;
            }
            if cy >= rows {
                scroll_up(fb, pitch, scr_w, scr_h, rows);
                cy = rows - 1;
            }
            draw_glyph(fb, pitch, cx * GLYPH_W, cy * GLYPH_H, c);
            cx += 1;
        }
    }

    if cy >= rows {
        scroll_up(fb, pitch, scr_w, scr_h, rows);
        cy = rows - 1;
    }

    CUR_X.store(cx, Ordering::Relaxed);
    CUR_Y.store(cy, Ordering::Relaxed);
}

/// Draw a single glyph at pixel position (px, py).
fn draw_glyph(fb: usize, pitch: u32, px: u32, py: u32, c: u8) {
    let glyph = font_glyph(c);
    let stride = pitch / 4;
    let base = fb as *mut u32;
    for row in 0..GLYPH_H {
        let bits = glyph[row as usize];
        for col in 0..GLYPH_W {
            let on = (bits >> (7 - col)) & 1 != 0;
            let color = if on { FG_COLOR } else { BG_COLOR };
            let offset = (py + row) * stride + (px + col);
            unsafe {
                *base.add(offset as usize) = color;
            }
        }
    }
}

/// Scroll the screen up by one text row (GLYPH_H pixels).
fn scroll_up(fb: usize, pitch: u32, scr_w: u32, scr_h: u32, _rows: u32) {
    let base = fb as *mut u8;
    let row_bytes = pitch;
    let copy_lines = scr_h - GLYPH_H;
    // Move all lines up by GLYPH_H pixels.
    unsafe {
        core::ptr::copy(
            base.add((GLYPH_H * row_bytes) as usize),
            base,
            (copy_lines * row_bytes) as usize,
        );
        // Clear the last GLYPH_H lines.
        let clear_start = base.add((copy_lines * row_bytes) as usize);
        core::ptr::write_bytes(clear_start, 0, (GLYPH_H * row_bytes) as usize);
    }
}

// ── 8×16 bitmap font ────────────────────────────────────────────────
//
// Each glyph is 16 bytes (one byte per row, MSB = leftmost pixel).
// Covers ASCII 0x20–0x7E (printable).  Based on the classic VGA/BIOS
// 8x16 font encoding.

fn font_glyph(c: u8) -> &'static [u8; 16] {
    let idx = if c >= 0x20 && c <= 0x7E {
        (c - 0x20) as usize
    } else {
        // Unprintable → render as filled block.
        95 // '~' - 0x20 = last entry, use block below
    };
    if idx < FONT_DATA.len() {
        &FONT_DATA[idx]
    } else {
        &FONT_DATA[0] // space
    }
}

